classdef ParsingTest < matlab.unittest.TestCase
    % These tests check the parsers on small hand-written inputs. They do
    % not stand in for data: the real check is run_demo_terminal_audit on
    % the official files, which stops if the recovered layout does not
    % match the logged state width.

    methods (Test)
        function jointLayoutOrderAndSizes(tc)
            xml = ['<mujoco><worldbody>', ...
                '<body name="robot0_base">', ...
                '  <body name="link1"><joint name="j1" type="hinge"/>', ...
                '    <body name="link2"><joint name="j2"/></body>', ...
                '  </body>', ...
                '</body>', ...
                '<body name="bowl_1_main"><joint name="bowl_1_joint0" type="free"/></body>', ...
                '<body name="cabinet_1_main">', ...
                '  <body name="drawer"><joint name="cabinet_1_slide" type="slide"/></body>', ...
                '</body>', ...
                '<body name="plate_1_main"><freejoint name="plate_1_joint0"/></body>', ...
                '</worldbody></mujoco>'];
            L = predaudit.mjcfJointLayout(xml);
            tc.verifyEqual(L.joints.joint.', ...
                ["j1" "j2" "bowl_1_joint0" "cabinet_1_slide" "plate_1_joint0"]);
            tc.verifyEqual(L.joints.type.', ["hinge" "hinge" "free" "slide" "free"]);
            tc.verifyEqual(L.joints.qposAdr.', [1 2 3 10 11]);
            tc.verifyEqual(L.joints.qvelAdr.', [1 2 3 9 10]);
            tc.verifyEqual([L.nq L.nv], [17 15]);
            tc.verifyEqual(L.joints.body(3), "bowl_1_main");
        end

        function ownJointsComeBeforeChildBodies(tc)
            xml = ['<mujoco><worldbody><body name="a">', ...
                '<body name="b"><joint name="jb"/></body>', ...
                '<joint name="ja"/>', ...
                '</body></worldbody></mujoco>'];
            L = predaudit.mjcfJointLayout(xml);
            tc.verifyEqual(L.joints.joint.', ["ja" "jb"]);
        end

        function goalPredicates(tc)
            bddl = ['(define (problem LIBERO_Kitchen) (:init (On plate_1 table)) ', ...
                '(:goal (And (On akita_black_bowl_1 plate_1) (Open wooden_cabinet_1_top_region))))'];
            g = predaudit.parseBddlGoal(bddl);
            tc.verifyEqual(g.predicate.', ["On" "Open"]);
            tc.verifyEqual(g.arg1.', ["akita_black_bowl_1" "wooden_cabinet_1_top_region"]);
            tc.verifyEqual(g.arg2.', ["plate_1" ""]);
        end

        function missingGoalIsAnError(tc)
            tc.verifyError(@() predaudit.parseBddlGoal('(define (problem x))'), ...
                'predaudit:parseBddlGoal:noGoal');
        end
    end
end
